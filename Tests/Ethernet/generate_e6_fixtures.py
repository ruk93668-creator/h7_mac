"""Regenerate the eight original Flash-only 160x120 JPEG fixtures (Pillow 12.2.0)."""
from io import BytesIO
from pathlib import Path
import zlib

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent / 'e6_jpeg_fixtures'


def build():
    ROOT.mkdir(exist_ok=True)
    frames = []
    for index in range(8):
        color = ((35 + 29 * index) % 235, (65 + 41 * index) % 235, (110 + 51 * index) % 235)
        image = Image.new('RGB', (160, 120), color)
        draw = ImageDraw.Draw(image)
        for y in range(0, 120, 10):
            for x in range(0, 160, 10):
                if ((x + y) // 10 + index) % 2:
                    draw.rectangle((x, y, x + 9, y + 9), fill=tuple((v + 70) % 256 for v in color))
        x = 8 + index * 17
        draw.ellipse((x, 34, x + 24, 58), fill=(255, 240, 30), outline=(5, 5, 5), width=2)
        draw.rectangle((0, 94, 159, 119), fill=(10, 20, 32))
        for step in range(8):
            draw.rectangle((7 + 19 * step, 102, 22 + 19 * step, 113),
                           fill=(255, 240, 30) if step == index else (90, 105, 130))
        output = BytesIO()
        image.save(output, format='JPEG', quality=75, subsampling=2, optimize=False, progressive=False)
        data = output.getvalue()
        (ROOT / f'frame{index}.jpg').write_bytes(data)
        frames.append(data)
    lines = ['/* Generated by generate_e6_fixtures.py. */', '#include "e6_jpeg_fixtures.h"', '']
    for index, data in enumerate(frames):
        lines.append(f'static const uint8_t e6_jpeg_{index}[] = {{')
        for offset in range(0, len(data), 16):
            lines.append('\t' + ', '.join(f'0x{value:02X}' for value in data[offset:offset+16]) + ',')
        lines.extend(('};', ''))
    lines += ['const EthMjpegFrame_t e6_jpeg_frames[E6_FRAME_COUNT] = {']
    for index, data in enumerate(frames):
        lines.append(f'\t{{e6_jpeg_{index}, sizeof(e6_jpeg_{index}), 0x{zlib.crc32(data):08X}U}},')
    lines.extend(('};', ''))
    (ROOT / 'e6_jpeg_fixtures.c').write_text('\n'.join(lines), encoding='ascii', newline='\n')


if __name__ == '__main__':
    build()
